"""Write .streamlit/secrets.toml for Google Sign-In from environment variables (container start).

Streamlit's native OIDC (st.login) reads its [auth] section only from secrets.toml, while a
container gets its configuration from environment variables. This bridges the two:

    EDUDSS_PUBLIC_URL            https://edudss.example.org   (redirect URI = <url>/oauth2callback)
    EDUDSS_GOOGLE_CLIENT_ID      OAuth client (Web application) from Google Cloud Console
    EDUDSS_GOOGLE_CLIENT_SECRET
    EDUDSS_AUTH_COOKIE_SECRET    random >= 32 chars, signs Streamlit's identity cookie

Missing values -> nothing is written and the login page shows only the password form.
The file is created with mode 600 and never printed.
"""
from __future__ import annotations

import json
import os
import sys
from pathlib import Path

APP_ROOT = Path(__file__).resolve().parents[1]


def build(env: dict) -> str | None:
    url = (env.get("EDUDSS_PUBLIC_URL") or "").strip().rstrip("/")
    client_id = (env.get("EDUDSS_GOOGLE_CLIENT_ID") or "").strip()
    client_secret = (env.get("EDUDSS_GOOGLE_CLIENT_SECRET") or "").strip()
    cookie = (env.get("EDUDSS_AUTH_COOKIE_SECRET") or "").strip()
    if not (url and client_id and client_secret):
        return None
    if not url.startswith("https://") and not url.startswith("http://localhost"):
        raise SystemExit("EDUDSS_PUBLIC_URL must be https:// (Google rejects other redirect URIs)")
    if len(cookie) < 32:
        raise SystemExit("EDUDSS_AUTH_COOKIE_SECRET must be at least 32 characters")
    q = json.dumps  # a JSON string is a valid TOML basic string
    return "\n".join([
        "# Generated by ops/write_streamlit_secrets.py at container start — do not edit or commit.",
        "[auth]",
        f"redirect_uri = {q(url + '/oauth2callback')}",
        f"cookie_secret = {q(cookie)}",
        "",
        "[auth.google]",
        f"client_id = {q(client_id)}",
        f"client_secret = {q(client_secret)}",
        'server_metadata_url = "https://accounts.google.com/.well-known/openid-configuration"',
        "",
    ])


def main() -> int:
    content = build(dict(os.environ))
    target = APP_ROOT / ".streamlit" / "secrets.toml"
    if content is None:
        print("[secrets] Google Sign-In not configured (password login only)")
        return 0
    target.parent.mkdir(parents=True, exist_ok=True)
    fd = os.open(target, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8") as f:
        f.write(content)
    print("[secrets] Google Sign-In configured")
    return 0


if __name__ == "__main__":
    sys.exit(main())
