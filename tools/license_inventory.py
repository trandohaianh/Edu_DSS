"""Generate / check THIRD_PARTY_NOTICES.md from requirements.lock.txt (C1.2).

    python tools/license_inventory.py            # regenerate app/THIRD_PARTY_NOTICES.md
    python tools/license_inventory.py --check    # CI: fail if the file is stale or a
                                                 # dependency has a blocked/unknown license

Run it in the production image (or an environment installed from the lock) so license
metadata comes from exactly the shipped distributions. This is an engineering inventory,
not a legal opinion.

License policy (engineering gate):
  BLOCKED  -> AGPL, GPL (non-LGPL), SSPL, Commons Clause, "proprietary"/unknown-without-review
  REVIEW   -> LGPL, MPL, EPL, CDDL (weak copyleft: fine when used unmodified as libraries;
              keep notices, do not statically embed modified copies)
  ALLOWED  -> MIT, BSD, Apache-2.0, ISC, PSF, Python-2.0, Unlicense, HPND, zlib, 0BSD
"""
from __future__ import annotations

import argparse
import importlib.metadata as md
import re
import sys
from pathlib import Path

APP = Path(__file__).resolve().parents[1]
LOCK = APP / "requirements.lock.txt"
OUT = APP / "THIRD_PARTY_NOTICES.md"

# Non-Python components shipped with or required by a deployment.
EXTRA_COMPONENTS = [
    ("sentence-transformers/all-MiniLM-L6-v2", "embedding model (downloaded at runtime)", "Apache-2.0",
     "https://huggingface.co/sentence-transformers/all-MiniLM-L6-v2"),
    ("python:3.11.16-slim-trixie", "container base image (Debian + CPython)", "PSF-2.0 / Debian component licenses",
     "https://hub.docker.com/_/python"),
    ("pgvector/pgvector:pg16", "database image (PostgreSQL + pgvector)", "PostgreSQL License",
     "https://github.com/pgvector/pgvector"),
    ("caddy:2", "reverse proxy image (deploy/production)", "Apache-2.0", "https://github.com/caddyserver/caddy"),
    ("Streamlit bundled web fonts (Source Sans / Source Code)", "UI fonts shipped inside the streamlit wheel",
     "SIL OFL 1.1", "https://github.com/adobe-fonts"),
]
BLOCKED = re.compile(r"\b(AGPL|Affero|SSPL|Commons Clause|proprietary)\b|\bGPL(?!.*Lesser)|GNU General Public", re.I)
REVIEW = re.compile(r"\b(LGPL|Lesser General|MPL|Mozilla|EPL|Eclipse|CDDL)\b", re.I)


def _norm(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def locked_packages() -> list[tuple[str, str]]:
    out = []
    for line in LOCK.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if line and not line.startswith("#") and "==" in line:
            name, version = line.split("==", 1)
            out.append((name, version))
    return sorted(out, key=lambda p: _norm(p[0]))


def license_of(name: str) -> str:
    try:
        meta = md.metadata(name)
    except md.PackageNotFoundError:
        return "NOT INSTALLED IN THIS ENVIRONMENT"
    expr = (meta.get("License-Expression") or "").strip()
    if expr:
        return expr
    classifiers = [c.split("::")[-1].strip() for c in meta.get_all("Classifier") or [] if c.startswith("License ::")]
    raw = (meta.get("License") or "").strip().splitlines()
    short = raw[0][:80] if raw and len(raw[0]) <= 80 else ""
    return "; ".join(dict.fromkeys([*classifiers, short] if short else classifiers)) or "UNKNOWN"


def classify(text: str) -> str:
    if text in ("UNKNOWN", "NOT INSTALLED IN THIS ENVIRONMENT"):
        return "REVIEW"
    if REVIEW.search(text):
        return "REVIEW"
    if BLOCKED.search(text):
        return "BLOCKED"
    return "ALLOWED"


def render() -> tuple[str, list[str]]:
    rows, blocked, review = [], [], []
    for name, version in locked_packages():
        lic = license_of(name)
        status = classify(lic)
        rows.append(f"| {name} | {version} | {lic.replace('|', '/')} | {status} |")
        if status == "BLOCKED":
            blocked.append(f"{name} ({lic})")
        elif status == "REVIEW":
            review.append(f"{name} ({lic})")
    lines = [
        "# Third-party notices — EduDSS",
        "",
        "Generated by `tools/license_inventory.py` from `requirements.lock.txt` and the installed",
        "distribution metadata of the production image. Engineering inventory only — not a legal",
        "opinion. Each component remains under its own license; full license texts are shipped",
        "inside each installed distribution (`*.dist-info/`) and at the listed upstream sources.",
        "",
        "## Python dependencies (production image)",
        "",
        "| Package | Version | License (from package metadata) | Policy |",
        "|---|---|---|---|",
        *rows,
        "",
        "## Models, images and bundled assets",
        "",
        "| Component | Role | License | Source |",
        "|---|---|---|---|",
        *[f"| {n} | {r} | {l} | {s} |" for n, r, l, s in EXTRA_COMPONENTS],
        "",
        "## Policy summary",
        "",
        f"- BLOCKED: {', '.join(blocked) if blocked else 'none'}",
        f"- REVIEW (weak copyleft or unknown metadata; used unmodified as libraries): "
        f"{', '.join(review) if review else 'none'}",
        "",
    ]
    return "\n".join(lines), blocked


def main(argv=None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--out", type=Path, default=OUT)
    args = parser.parse_args(argv)
    content, blocked = render()
    if args.check:
        current = args.out.read_text(encoding="utf-8") if args.out.exists() else ""
        stale = current.strip() != content.strip()
        if stale:
            print("THIRD_PARTY_NOTICES.md is stale: regenerate with `python tools/license_inventory.py`")
        if blocked:
            print("BLOCKED licenses:", ", ".join(blocked))
        return 1 if stale or blocked else 0
    args.out.write_text(content, encoding="utf-8")
    print(f"wrote {args.out.name}: {len(locked_packages())} packages, blocked={len(blocked)}")
    return 1 if blocked else 0


if __name__ == "__main__":
    sys.exit(main())
